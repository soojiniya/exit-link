"""Deterministic OpenAPI, WebSocket JSON Schema and TS contracts; no Node dependency."""
import json
import re
from pathlib import Path
from typing import Annotated

from pydantic import Field, TypeAdapter

from exit_link.api.contracts import (DeliveryObserved, ExperimentChanged, FaultObserved, NetworkChanged,
    RouteChanged, ScenarioChanged, SnapshotFrame)
from exit_link.api.security import ApiSettings
from exit_link.main import create_app

Frame = Annotated[SnapshotFrame | ScenarioChanged | RouteChanged | NetworkChanged | FaultObserved |
                  DeliveryObserved | ExperimentChanged, Field(discriminator="type")]


def name(raw):
    return re.sub(r"\W", "_", raw)


def ts(schema, prefix="", complete=False):
    if schema is True:
        return "unknown"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return prefix + name(schema["$ref"].rsplit("/", 1)[1])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    for key, join in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + join.join(ts(item, prefix, complete) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema.get("items", {}), prefix, complete) + ">"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if not properties:
            extra = schema.get("additionalProperties", True)
            return "Record<string, " + ts(extra, prefix, complete) + ">"
        required = set(properties) if complete else set(schema.get("required", []))
        fields = [json.dumps(key) + ("" if key in required else "?") + ": " + ts(value, prefix, complete)
                  for key, value in properties.items()]
        extra = schema.get("additionalProperties", False)
        if extra is not False:
            fields.append("[key: string]: unknown")
        return "{ " + "; ".join(fields) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def artifacts():
    app = create_app(ApiSettings(monitor_enabled=False))
    spec = app.openapi()
    ws_schema = TypeAdapter(Frame).json_schema(mode="serialization")
    output = ["// Generated by scripts/export_stage5_contracts.py. Do not edit.",
              "// UUID/date-time => string; numbers use JSON units in API docs.",
              "// REST defaults are optional on input. Ws* fields describe complete model_dump output.\n"]
    for key, model in sorted(spec["components"]["schemas"].items()):
        output.append(f"export type {name(key)} = {ts(model)};")
    output.append("\nexport interface Operations {")
    for path, operations in sorted(spec["paths"].items()):
        for method, operation in sorted(operations.items()):
            if method not in {"get", "post", "put", "delete"}:
                continue
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            success = next((value for code, value in operation["responses"].items() if code.startswith("2")), {})
            response = success.get("content", {}).get("application/json", {}).get("schema", {})
            fields = [] if body is None else ["body: " + ts(body)]
            for place in ("path", "query"):
                params = {p["name"]: p["schema"] for p in operation.get("parameters", []) if p["in"] == place}
                required = [p["name"] for p in operation.get("parameters", []) if p["in"] == place and p.get("required")]
                if params:
                    fields.append(place + ": " + ts({"type": "object", "properties": params, "required": required}))
            fields.append("response: " + ts(response))
            output.append("  " + json.dumps(method.upper() + " " + path) + ": { " + "; ".join(fields) + " };")
    output.append("}\n")
    for key, model in sorted(ws_schema.get("$defs", {}).items()):
        output.append(f"export type Ws{name(key)} = {ts(model, 'Ws', complete=True)};")
    output.append("\nexport type ServerFrame = " + ts(ws_schema, "Ws", complete=True) + ";\n")
    render = lambda data: json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    return {"openapi.json": render(spec), "WebSocket.schema.json": render(ws_schema), "types.ts": "\n".join(output)}


def main():
    output = Path(__file__).resolve().parents[1] / "docs/contracts/stage5"
    output.mkdir(parents=True, exist_ok=True)
    for filename, content in artifacts().items():
        (output / filename).write_text(content, encoding="utf-8")
    print(f"Exported OpenAPI, WebSocket schema and TypeScript: {output}")


if __name__ == "__main__":
    main()
